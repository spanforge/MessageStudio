import { expect, test, type Page } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { browserPaste } from './helpers';
const source = (p: Page) => p.getByRole('textbox',{name:'Post source editor'});
async function link(page: Page) {
  await source(page).focus(); await source(page).evaluate(browserPaste,{plain:'18 October · unbound 18 October'});
  await page.keyboard.press('Home'); for (let i=0;i<10;i++) await page.keyboard.press('Shift+ArrowRight');
  await page.getByRole('button',{name:'Shared details',exact:true}).click();
  await page.getByLabel('Label',{exact:true}).fill('Launch date');
  await page.getByRole('button',{name:'Keep selected text consistent'}).click();
  await page.getByRole('button',{name:'Apply reviewed change'}).click();
}
test.beforeEach(async ({page}) => { await page.goto('/'); await expect(source(page)).toBeVisible(); });
test('typed date review preserves unlinked wording, channel formats, reload and full backup',async ({page}) => {
  await link(page);
  await page.getByRole('button',{name:'Shared details',exact:true}).click();
  await page.getByLabel('Fact type',{exact:true}).selectOption('date');
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-10-18');
  await page.getByText('Channel display formats',{exact:true}).click();
  await page.getByLabel('Month display',{exact:true}).selectOption('long');
  await page.getByLabel('Include calculated weekday',{exact:true}).check();
  await page.getByRole('button',{name:'Preview typed fact change'}).click();
  await page.getByRole('button',{name:'Apply reviewed change'}).click();
  await page.getByLabel('Destination',{exact:true}).selectOption('whatsapp');
  await expect(page.getByTestId('export-output')).toContainText('Sunday');
  await expect(page.getByTestId('export-output')).toContainText('unbound 18 October');
  await page.getByRole('button',{name:'Campaign: Create or import'}).click();
  await page.getByLabel('Campaign title',{exact:true}).fill('October workshop');
  await page.getByRole('button',{name:'Create campaign from this draft'}).click();
  await expect(page.getByRole('heading',{name:'October workshop',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await expect(page.locator('.save-status')).toContainText('Saved locally');
  await page.reload(); await expect(page.getByRole('button',{name:'Campaign: October workshop'})).toBeVisible();
  await expect(page.getByTestId('export-output')).toContainText('Sunday');
  await page.getByRole('button',{name:'Shared details',exact:true}).click();
  await page.getByLabel('Calendar date',{exact:true}).fill('2026-10-19');
  await page.getByRole('button',{name:'Preview typed fact change'}).click();
  await page.getByRole('button',{name:'Apply reviewed change'}).click();
  await expect(page.getByTestId('export-output')).toContainText('Monday');
  await expect(page.getByTestId('export-output')).toContainText('unbound 18 October');
  await page.getByRole('button',{name:'Undo reviewed change',exact:true}).click();
  await expect(page.getByTestId('export-output')).toContainText('Sunday');
  await page.getByRole('button',{name:/Drafts/}).click();
  const download = page.waitForEvent('download'); await page.getByRole('button',{name:'Backup all drafts'}).click();
  const file = await download; const stream = await file.createReadStream(); const chunks: Buffer[] = []; for await (const chunk of stream!) chunks.push(Buffer.from(chunk));
  const backup = JSON.parse(Buffer.concat(chunks).toString());
  expect(backup.campaigns[0].campaign.title).toBe('October workshop');
  expect(backup.campaigns[0].facts[0].value).toEqual({type:'date',date:'2026-10-18'});
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.locator('input[type=file]').setInputFiles({name:'campaign-workspace.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await page.getByRole('button',{name:'Add as new drafts',exact:true}).click();
  await expect(page.getByRole('button',{name:'Campaign: October workshop'})).toBeVisible();
  await expect(page.getByTestId('export-output')).toContainText('Sunday');
});
test('invalid typed values do not alter source and the fact dialog remains accessible on mobile',async ({page}) => {
  await link(page); await page.setViewportSize({width:360,height:800});
  await page.getByRole('button',{name:'Shared details',exact:true}).click();
  await page.getByLabel('Fact type',{exact:true}).selectOption('money'); await page.getByLabel('Decimal amount',{exact:true}).fill('1e3');
  await page.getByRole('button',{name:'Preview typed fact change'}).click();
  await expect(page.getByRole('dialog')).toHaveCount(1);
  await expect(source(page)).toHaveText('18 October · unbound 18 October');
  expect((await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()).violations).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
